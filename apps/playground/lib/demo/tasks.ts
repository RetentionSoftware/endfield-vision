import type { Tone } from 'endfield-vision'

export type TaskStatus = 'new' | 'in_progress' | 'review' | 'blocked' | 'done'
export type Priority = 'low' | 'normal' | 'high' | 'critical'

export interface ChecklistItem {
  id: string
  text: string
  done: boolean
}

export interface TaskComment {
  id: string
  authorId: string
  text: string
  /** ISO с временем. */
  at: string
}

export interface Task {
  id: string
  title: string
  facilityId: string
  assigneeId: string
  authorId: string
  priority: Priority
  status: TaskStatus
  /** YYYY-MM-DD. */
  due: string
  createdAt: string
  description: string
  checklist: ChecklistItem[]
  comments: TaskComment[]
}

/** «Сегодня» демо-консоли: просрочка считается от этой даты. */
export const TODAY = '2026-10-08'

export const TASK_STATUS: Record<TaskStatus, { label: string; tone: Tone }> = {
  new: { label: 'Новая', tone: 'info' },
  in_progress: { label: 'В работе', tone: 'accent' },
  review: { label: 'На проверке', tone: 'violet' },
  blocked: { label: 'Заблокирована', tone: 'danger' },
  done: { label: 'Выполнена', tone: 'success' },
}

export const PRIORITY: Record<Priority, { label: string; tone: Tone }> = {
  low: { label: 'Низкий', tone: 'neutral' },
  normal: { label: 'Обычный', tone: 'info' },
  high: { label: 'Высокий', tone: 'warning' },
  critical: { label: 'Критический', tone: 'danger' },
}

export const PRIORITY_ORDER: Record<Priority, number> = { low: 0, normal: 1, high: 2, critical: 3 }

export const STATUS_ORDER: TaskStatus[] = ['new', 'in_progress', 'review', 'blocked', 'done']

/** Прогресс задачи: выполненная - 100%, иначе доля пунктов чек-листа. */
export function taskProgress(t: Task): number {
  if (t.status === 'done') return 100
  if (t.checklist.length === 0) return 0
  return Math.round((t.checklist.filter((c) => c.done).length / t.checklist.length) * 100)
}

export function isOverdue(t: Task): boolean {
  return t.status !== 'done' && t.due < TODAY
}

